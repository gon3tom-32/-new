// Builds supabase/twelve_content.sql from packs.json.
// Run from the repository root: node supabase/content/build.mjs
//
// Choices are shuffled with a fixed seed, so running this again gives the
// same file unless packs.json changes.
import { readFileSync, writeFileSync } from "node:fs";

const here = new URL(".", import.meta.url);
const packs = JSON.parse(readFileSync(new URL("packs.json", here), "utf8"));

function seededRandom(seedText) {
  let seed = 0;
  for (const ch of seedText) seed = (seed * 31 + ch.charCodeAt(0)) >>> 0;
  return () => {
    seed = (seed + 0x6d2b79f5) >>> 0;
    let t = seed;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffle(items, random) {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

// Quiz rows are [prompt, rightAnswer, ...wrongAnswers].
function quiz(format, pack, index) {
  const random = seededRandom(`${format}:${index}`);
  const questions = [];
  const correct = [];
  for (const [prompt, ...choices] of pack.questions) {
    const order = shuffle(choices.map((_, i) => i), random);
    questions.push({ prompt, choices: order.map((i) => choices[i]) });
    correct.push(order.indexOf(0));
  }
  return { content: { intro: pack.intro, questions }, answers: { correct } };
}

function build(format, pack, index) {
  switch (format) {
    case "trivia":
    case "emoji":
    case "two_truths":
    case "lyrics":
      return quiz(format, pack, index);
    case "bingo":
      if (pack.squares.length !== 24) throw new Error(`${pack.title}: bingo needs 24 squares`);
      return { content: { intro: pack.intro, squares: pack.squares }, answers: null };
    case "scavenger":
      return { content: { intro: pack.intro, items: pack.items }, answers: null };
    case "photo":
      return { content: { intro: pack.intro, prompt: pack.prompt, tips: pack.tips }, answers: null };
    case "wyr":
      return {
        content: { intro: pack.intro, questions: pack.questions.map(([a, b]) => ({ a, b })) },
        answers: null,
      };
    case "speed_match": {
      const random = seededRandom(`speed:${index}`);
      const rights = shuffle(pack.pairs.map(([, right]) => right), random);
      return {
        content: {
          intro: pack.intro,
          left_label: pack.left_label,
          right_label: pack.right_label,
          lefts: pack.pairs.map(([left]) => left),
          rights,
        },
        answers: { correct: pack.pairs.map(([, right]) => rights.indexOf(right)) },
      };
    }
    case "finale":
      return { content: { intro: pack.intro }, answers: null };
    default:
      throw new Error(`Unknown format ${format}`);
  }
}

const sqlText = (value) => "'" + String(value).replaceAll("'", "''") + "'";
const sqlJson = (value) => (value == null ? "null" : sqlText(JSON.stringify(value)) + "::jsonb");

const rows = [];
for (const [format, list] of Object.entries(packs)) {
  if (format.startsWith("_")) continue;
  list.forEach((pack, i) => {
    const { content, answers } = build(format, pack, i);
    rows.push(`  (${sqlText(format)}, ${i + 1}, ${sqlText(pack.title)}, ${sqlJson(content)}, ${sqlJson(answers)})`);
  });
}

const sql = `-- Built-in game content for Twelve. Run this after twelve.sql
-- (SQL Editor → New query → paste → Run). Safe to run again.
--
-- Generated by supabase/content/build.mjs from supabase/content/packs.json.
-- Edit packs.json and rebuild rather than editing this file.

insert into public.twelve_game_packs (format, pack, title, content, answers)
values
${rows.join(",\n")}
on conflict (format, pack) do update set
  title = excluded.title,
  content = excluded.content,
  answers = excluded.answers;
`;

writeFileSync(new URL("../twelve_content.sql", here), sql);
console.log(`Wrote ${rows.length} packs to supabase/twelve_content.sql`);
